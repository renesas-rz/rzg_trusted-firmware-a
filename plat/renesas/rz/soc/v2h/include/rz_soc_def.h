#ifndef __RZ_SOC_DEF_H__
#define __RZ_SOC_DEF_H__

#define RZV2H_BOOT_ROM_BASE			(0x00000000UL)
#define RZV2H_MSRAM_BASE			(0x08000000UL)
#define RZV2H_ASRAM_BASE			(0x08100000UL)
#define RZV2H_R8SRAM_BASE			(0x08180000UL)
#define RZV2H_DEVICE_BASE			(0x10000000UL)
#define RZV2H_ELC					(0x10400000UL)
#define RZV2H_GPIO_BASE				(0x10410000UL)
#define RZV2H_CPG_BASE				(0x10420000UL)
#define RZV2H_SYSC_BASE				(0x10430000UL)
#define RZV2H_TSIP_BASE				(0x10440000UL)
#define RZV2H_OTP_BASE				(0x10450000UL)
#define RZV2H_TZC400_M33_BASE		(0x10460000UL)
#define RZV2H_TZC400_xSPI_BASE		(0x10470000UL)
#define RZV2H_MHU_BASE				(0x10480000UL)
#define RZV2H_CLMA1_BASE			(0x10490000UL)
#define RZV2H_CLMA0_BASE			(0x104A0000UL)
#define RZV2H_CST_BASE				(0x10800000UL)
#define RZV2H_MCPU_SYS_BASE			(0x10C00000UL)
#define RZV2H_TSU0_BASE				(0x11000000UL)
#define RZV2H_TSU1_BASE				(0x11001000UL)
#define RZV2H_XSPI_BASE				(0x11030000UL)

#define RZV2H_SCIF_BASE				(0x11C01400UL)

#define RZV2H_TZC400_DDR00_BASE		(0x13C60000UL)
#define RZV2H_TZC400_DDR01_BASE		(0x13C70000UL)
#define RZV2H_TZC400_DDR10_BASE		(0x13C80000UL)
#define RZV2H_TZC400_DDR11_BASE		(0x13C90000UL)
#define RZV2H_TZC400_R8_BASE		(0x13CA0000UL)
#define RZV2H_TZC400_A55_BASE		(0x13CB0000UL)
#define RZV2H_TZC400_PCIe_BASE		(0x13CC0000UL)

#define RZV2H_SYC_BASE				(0x14010000UL)

#define RZV2H_GIC_BASE				(0x14900000UL)

#define RZV2H_SD0_BASE				(0x15C00000UL)
#define RZV2H_SD1_BASE				(0x15C10000UL)
#define RZV2H_SD2_BASE				(0x15C20000UL)

#define RZV2H_DDR0_PHY_BASE			(0x1A000000UL)
#define RZV2H_DDR1_PHY_BASE			(0x1C000000UL)
#define RZV2H_DDR0_MEMC_BASE		(0x1E000000UL)
#define RZV2H_DDR1_MEMC_BASE		(0x1E010000UL)

#define RZV2H_XSPI_MEMORY_MAP_BASE	(0x20000000UL)
#define RZV2H_PCIe_MIRROR_BASE		(0x30000000ULL)
#define RZV2H_DDR0_BASE             (0x40000000ULL)
#define RZV2H_DDR1_BASE             (0x240000000ULL)
#define RZV2H_PCIe0_BASE            (0x440000000ULL)
#define RZV2H_PCIe1_BASE            (0xA40000000ULL)

#define RZV2H_DDR_MEMC_BASE			RZV2H_DDR0_MEMC_BASE	//TODO: KTG: Remove, temporary scaffold code
#define RZV2H_DDR_PHY_BASE			RZV2H_DDR0_PHY_BASE		//TODO: KTG: Remove, temporary scaffold code

#define RZV2H_SPIROM_BASE			RZV2H_XSPI_MEMORY_MAP_BASE

#define RZV2H_GICD_BASE				(RZV2H_GIC_BASE)				//TODO: KTG: Update
#define RZV2H_GICR_BASE				(RZV2H_GIC_BASE + 0x00040000)	//TODO: KTG: Update

#define RZV2H_SRAM_BASE				(RZV2H_MSRAM_BASE)

#define RZV2H_SRAM_SIZE				(0x00080000UL)
#define RZV2H_BOOT_ROM_SIZE			(0x00020000UL - RZV2H_BOOT_ROM_BASE)
#define RZV2H_MSRAM_SIZE			(RZV2H_SRAM_SIZE*2)
#define RZV2H_ASRAM_SIZE			(RZV2H_SRAM_SIZE)
#define RZV2H_R8SRAM_SIZE			(RZV2H_SRAM_SIZE)
#define RZV2H_DEVICE_SIZE			(0x20000000UL - RZV2H_DEVICE_BASE)
#define RZV2H_SPIROM_SIZE			(RZV2H_PCIe_MIRROR_BASE - RZV2H_XSPI_MEMORY_MAP_BASE)
#define RZV2H_DDR0_SIZE             (RZV2H_DDR1_BASE - RZV2H_DDR0_BASE)
#define RZV2H_DDR1_SIZE             (RZV2H_PCIe0_BASE - RZV2H_DDR1_BASE)

/*
 *  0x20000 has been chosen as FIP base as that leaves room at start of xSPI Flash
 * to store a 128K BL2 image.
 */
#define RZV2H_BL2_SIZE_MAX			(0x00020000U)	/* This value is not checked/enforced anywhwere */
#define RZV2H_SPIROM_FIP_BASE		(RZV2H_XSPI_MEMORY_MAP_BASE + RZV2H_BL2_SIZE_MAX)
#define RZV2H_SPIROM_FIP_SIZE		(RZV2H_PCIe_MIRROR_BASE - RZV2H_SPIROM_FIP_BASE)

#define RZV2H_EMMC_FIP_BASE			(PARAMS_BASE + PARAMS_SIZE)				//TODO: KTG: Confirm
#define RZV2H_EMMC_FIP_SIZE			(0x00078000UL) 						    //TODO: KTG: Confirm

#define RZV2H_SYC_INCK_HZ			(24000000UL)							//TODO: KTG: Update
#define RZV2H_UART_INCK_HZ			(100000000UL)							//TODO: KTG: Update	
#define RZV2H_UART_BARDRATE			(115200UL)

/* Boot Info base address for BL2 */
#define RZV2H_BOOTINFO_BASE			(RZV2H_ASRAM_BASE)
#define RZV2H_BOOTINFO_SIZE			(0x3000)

/* Definitions used in common code */

/* Base address where parameters to BL31 are stored */
#define PARAMS_BASE					(0x08104000 + RZV2H_BL2_SIZE_MAX)		//TODO: KTG: Confirm
#define PARAMS_SIZE					(0x1000UL)								//TODO: KTG: Confirm

#define RZ_SOC_BOOTINFO_BASE		RZV2H_BOOTINFO_BASE

#define RZ_SOC_SYC_BASE				RZV2H_SYC_BASE

#define RZ_SOC_GICD_BASE			RZV2H_GICD_BASE
#define RZ_SOC_GICR_BASE			RZV2H_GICR_BASE

#define RZ_SOC_SPIROM_FIP_BASE		RZV2H_SPIROM_FIP_BASE
#define RZ_SOC_SPIROM_FIP_SIZE		RZV2H_SPIROM_FIP_SIZE

#define RZ_SOC_EMMC_FIP_BASE		RZV2H_EMMC_FIP_BASE
#define RZ_SOC_EMMC_FIP_SIZE		RZV2H_EMMC_FIP_SIZE

#define RZ_SOC_SYSC_BASE_DEVID		SYS_LSI_DEVID
#define RZ_SOC_OTP_BASE_DEVID		(RZV2H_OTP_BASE + 0x1174)		/* OTPPRODUCT */
#define RZ_SOC_OTP_BASE_CHIPID		(RZV2H_OTP_BASE + 0x114C)		/* OTPCPID0 */

#define SYS_BASE					RZV2H_SYSC_BASE
#define PFC_BASE					RZV2H_GPIO_BASE
#define CPG_BASE					RZV2H_CPG_BASE
#define XSPI_BASE					RZV2H_XSPI_BASE

/* eMMC registers */
#define MMC0_SD_BASE				RZV2H_SD0_BASE
#define MMC1_SD_BASE				RZV2H_SD1_BASE
#define MMC2_SD_BASE				RZV2H_SD2_BASE

#endif /* __RZ_SOC_DEF_H__ */
