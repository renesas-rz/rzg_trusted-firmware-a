#ifndef __RZ_SOC_DEF_H__
#define __RZ_SOC_DEF_H__

#include <lib/utils_def.h>

#define RZG3E_BOOT_ROM_BASE			UL(0x00000000)
#define RZG3E_SRAM0_BASE			UL(0x08000000)
#define RZG3E_SRAM1_BASE			UL(0x08040000)

#define RZG3E_DEVICE_BASE			UL(0x10000000)

#define RZG3E_ELC					UL(0x10400000)
#define RZG3E_PFC_BASE				UL(0x10410000)
#define RZG3E_CPG_BASE				UL(0x10420000)
#define RZG3E_SYSC_BASE				UL(0x10430000)

#define RZG3E_OTP_BASE				UL(0x10450000)
#define RZG3E_TZC400_SRAM_BASE		UL(0x10460000)
#define RZG3E_TZC400_XSPI_BASE		UL(0x10470000)
#define RZG3E_MHU_BASE				UL(0x10480000)

#define RZG3E_XSPI_BASE				UL(0x11030000)

#define RZG3E_SCIF_BASE				UL(0x11C01400)

#define RZG3E_TZC400_DDR_0_BASE		UL(0x13C60000)
#define RZG3E_TZC400_DDR_1_BASE		UL(0x13C70000)
#define RZG3E_TZC400_RCPU_BASE		UL(0x13CA0000)

#define RZG3E_TZC400_PCIe_BASE		UL(0x13CC0000)

#define RZG3E_SYC_BASE				UL(0x14010000)

#define RZG3E_I2C_0_BASE			UL(0x14400400)
#define RZG3E_I2C_1_BASE			UL(0x14400800)
#define RZG3E_I2C_2_BASE			UL(0x14400C00)
#define RZG3E_I2C_8_BASE			UL(0x11C01000)

#define RZG3E_GIC_BASE				UL(0x14900000)
#define RZG3E_GICD_BASE				(RZG3E_GIC_BASE)
#define RZG3E_GICR_BASE				(RZG3E_GIC_BASE + 0x00040000)

#define RZG3E_SD0_BASE				UL(0x15C00000)
#define RZG3E_SD1_BASE				UL(0x15C10000)
#define RZG3E_SD2_BASE				UL(0x15C20000)

#define RZG3E_DDR_PHY_BASE			UL(0x1A000000)
#define RZG3E_DDR_MEMC_BASE			UL(0x1E000000)

#define RZ_SOC_DDR_PHY_BASE			RZG3E_DDR_PHY_BASE
#define RZ_SOC_DDR_MC_BASE			RZG3E_DDR_MEMC_BASE

#define RZG3E_XSPI_MEMORY_MAP_BASE	ULL(0x20000000)
#define RZG3E_PCIe_MIRROR_BASE		ULL(0x30000000)
#define RZG3E_DDR_BASE				ULL(0x40000000)
#define RZG3E_PCIe_BASE				ULL(0x440000000)


#define RZG3E_DDR_SIZE				ULL(0x40000000)
#define RZG3E_SRAM0_SIZE			UL(0x00040000)
#define RZG3E_SRAM1_SIZE			UL(0x00040000)
#define RZG3E_SRAM_COMBINED_SIZE	(RZG3E_SRAM0_SIZE + RZG3E_SRAM1_SIZE)
#define RZG3E_BOOT_ROM_SIZE			UL(0x00020000)
#define RZG3E_DEVICE_SIZE			(0x20000000 - RZG3E_DEVICE_BASE)
#define RZG3E_XSPI_SIZE				(0x30000000 - RZG3E_XSPI_MEMORY_MAP_BASE)

/* 0x00060000 = 384 KB This value is not checked/enforced anywhere */
#define RZG3E_BL2_SIZE_MAX			UL(0x00060000)
/*
 * eSD boot mode has 4096 sectors. Therefore 4096 x 512bytes = 0x1000 x 0x200 = 0x200000= 2MB.
 * 0x200000 - FIP start offset (RZG3E_BL2_END_OFFSET) = 0x200000 - 0x60000 = 0x1A0000 = 1664KB
 */
#define RZG3E_FIP_SIZE_MAX			UL(0x001A0000)

#define RZG3E_SPIROM_FIP_BASE		(RZG3E_XSPI_MEMORY_MAP_BASE + RZG3E_BL2_SIZE_MAX)
#define RZG3E_SPIROM_FIP_SIZE		RZG3E_FIP_SIZE_MAX

#define RZG3E_EMMC_FIP_BASE			RZG3E_BL2_SIZE_MAX
#define RZG3E_EMMC_FIP_SIZE			RZG3E_FIP_SIZE_MAX

#define RZG3E_SD_FIP_BASE			RZG3E_BL2_SIZE_MAX
#define RZG3E_SD_FIP_SIZE			RZG3E_FIP_SIZE_MAX

#define RZG3E_SYC_INCK_HZ			UL(24000000)

#define RZG3E_UART_INCK_HZ			UL(100000000)

#define RZG3E_UART_BAUDRATE			UL(115200)

#define RZ_SOC_SYC_BASE				RZG3E_SYC_BASE

#define RZ_SOC_GICD_BASE			RZG3E_GICD_BASE
#define RZ_SOC_GICR_BASE			RZG3E_GICR_BASE

#define RZ_SOC_SPIROM_FIP_BASE		RZG3E_SPIROM_FIP_BASE
#define RZ_SOC_SPIROM_FIP_SIZE		RZG3E_SPIROM_FIP_SIZE

#define RZ_SOC_EMMC_FIP_BASE		RZG3E_EMMC_FIP_BASE
#define RZ_SOC_EMMC_FIP_SIZE		RZG3E_EMMC_FIP_SIZE

#define RZ_SOC_SD_FIP_BASE			RZG3E_SD_FIP_BASE
#define RZ_SOC_SD_FIP_SIZE			RZG3E_SD_FIP_SIZE

#define RZG3E_DDR_CONFIG_MAX			UL(0x00001000)
#define RZG3E_SPIROM_DDR_CFG_BASE		(RZG3E_SPIROM_FIP_BASE + RZG3E_FIP_SIZE_MAX)
#define RZG3E_EMMC_DDR_CFG_BASE			(RZG3E_EMMC_FIP_BASE + RZG3E_FIP_SIZE_MAX)
#define RZG3E_SD_DDR_CFG_BASE			(RZG3E_SD_FIP_BASE + RZG3E_FIP_SIZE_MAX)

#define RZ_SOC_SPIROM_DDR_CFG_BASE		RZG3E_SPIROM_DDR_CFG_BASE
#define RZ_SOC_SPIROM_DDR_CFG_SIZE		RZG3E_DDR_CONFIG_MAX
#define RZ_SOC_EMMC_DDR_CFG_BASE		RZG3E_EMMC_DDR_CFG_BASE
#define RZ_SOC_EMMC_DDR_CFG_SIZE		RZG3E_DDR_CONFIG_MAX
#define RZ_SOC_SD_DDR_CFG_BASE			RZG3E_SD_DDR_CFG_BASE
#define RZ_SOC_SD_DDR_CFG_SIZE			RZG3E_DDR_CONFIG_MAX

#define RZ_SOC_OTP_BASE_PRODUCTID	SYS_LSI_PRR						/* OTPPRODUCT */

/* Error Interrupt CM33 Status Register k */
#define RZG3E_ELC_ERINTM33CTL(k)	(RZG3E_ELC + 0x0304 + ((k) * 0x004))

/* Error Interrupt CM33 Status Clear Register k */
#define RZG3E_ELC_ERINTM33CLR(k)	(RZG3E_ELC + 0x0314 + ((k) * 0x004))

/* Error Interrupt CA55 Status Register k */
#define RZG3E_ELC_ERINTA55CTL(k)	(RZG3E_ELC + 0x0338 + ((k) * 0x004))

/* Error Interrupt CA55 Status Clear Register k */
#define RZG3E_ELC_ERINTA55CLR(k)	(RZG3E_ELC + 0x0348 + ((k) * 0x004))


/*
 * TODO: check value when manual is updated.
 */
#define RZ_SOC_OTP_BASE_CHIPID		(RZG3E_OTP_BASE + 0x114C)		/* OTPCPID0 */

#define SYS_BASE					RZG3E_SYSC_BASE
#define PFC_BASE					RZG3E_PFC_BASE
#define CPG_BASE					RZG3E_CPG_BASE
#define XSPI_BASE					RZG3E_XSPI_BASE

/* eMMC registers */
#define MMC0_SD_BASE				RZG3E_SD0_BASE
#define MMC1_SD_BASE				RZG3E_SD1_BASE
#define MMC2_SD_BASE				RZG3E_SD2_BASE

#endif /* __RZ_SOC_DEF_H__ */
