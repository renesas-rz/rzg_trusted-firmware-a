#ifndef __RZ_SOC_DEF_H__
#define __RZ_SOC_DEF_H__

#define RZG3S_BOOT_ROM_BASE			(0x00000000UL)
#define RZG3S_MSRAM_BASE			(0x08000000UL)
#define RZG3S_ASRAM_BASE			(0x08100000UL)
#define RZG3S_DEVICE_BASE			(0x10000000UL)
#define RZG3S_GPIO_BASE				(0x10410000UL)
#define RZG3S_CPG_BASE				(0x10420000UL)
#define RZG3S_SYSC_BASE				(0x10430000UL)
#define RZG3S_OTP_BASE				(0x10450000UL)
#define RZG3S_TZC400_M33_BASE		(0x10460000UL)
#define RZG3S_TZC400_xSPI_BASE		(0x10470000UL)
#define RZG3S_MHU_BASE				(0x10480000UL)
#define RZG3S_CLMA1_BASE			(0x10490000UL)
#define RZG3S_CLMA0_BASE			(0x104A0000UL)
#define RZG3S_CST_BASE				(0x10800000UL)
#define RZG3S_MCPU_SYS_BASE			(0x10C00000UL)
#define RZG3S_TSU0_BASE				(0x11000000UL)
#define RZG3S_TSU1_BASE				(0x11001000UL)
#define RZG3S_XSPI_BASE				(0x11030000UL)

#define RZG3S_SCIF_BASE				(0x11C01400UL)

#define RZG3S_TZC400_DDR00_BASE		(0x13C60000UL)
#define RZG3S_TZC400_DDR01_BASE		(0x13C70000UL)
#define RZG3S_TZC400_DDR10_BASE		(0x13C80000UL)
#define RZG3S_TZC400_DDR11_BASE		(0x13C90000UL)
#define RZG3S_TZC400_A55_BASE		(0x13CB0000UL)
#define RZG3S_TZC400_PCIe_BASE		(0x13CC0000UL)

#define RZG3S_SYC_BASE				(0x14010000UL)

#define RZG3S_GIC_BASE				(0x14900000UL)

#define RZG3S_SD0_BASE				(0x15C00000UL)
#define RZG3S_SD1_BASE				(0x15C10000UL)
#define RZG3S_SD2_BASE				(0x15C20000UL)

#define RZG3S_DDR0_PHY_BASE			(0x1A000000UL)
#define RZG3S_DDR1_PHY_BASE			(0x1C000000UL)
#define RZG3S_DDR0_MEMC_BASE		(0x1E000000UL)
#define RZG3S_DDR1_MEMC_BASE		(0x1E010000UL)

#define RZG3S_XSPI_MEMORY_MAP_BASE	(0x20000000UL)
#define RZG3S_PCIe_MIRROR_BASE		(0x30000000ULL)
#define RZG3S_DDR0_BASE				(0x40000000ULL)
#define RZG3S_DDR1_BASE				(0x240000000ULL)
#define RZG3S_PCIe0_BASE			(0x440000000ULL)
#define RZG3S_PCIe1_BASE			(0xA40000000ULL)

#define RZG3S_DDR_MEMC_BASE			RZG3S_DDR0_MEMC_BASE
#define RZG3S_DDR_PHY_BASE			RZG3S_DDR0_PHY_BASE

#define RZG3S_SPIROM_BASE			RZG3S_XSPI_MEMORY_MAP_BASE

#define RZG3S_GICD_BASE				(RZG3S_GIC_BASE)				//TODO: KTG: Confirm
#define RZG3S_GICR_BASE				(RZG3S_GIC_BASE + 0x00040000)	//TODO: KTG: Confirm

#define RZG3S_SRAM_BASE				(RZG3S_MSRAM_BASE)

#define RZG3S_SRAM_SIZE				(0x00080000UL)
#define RZG3S_BOOT_ROM_SIZE			(0x00020000UL - RZG3S_BOOT_ROM_BASE)
#define RZG3S_MSRAM_SIZE			(RZG3S_SRAM_SIZE*2)
#define RZG3S_ASRAM_SIZE			(RZG3S_SRAM_SIZE)
#define RZG3S_DEVICE_SIZE			(0x20000000UL - RZG3S_DEVICE_BASE)
#define RZG3S_SPIROM_SIZE			(RZG3S_PCIe_MIRROR_BASE - RZG3S_XSPI_MEMORY_MAP_BASE)
#define RZG3S_DDR0_SIZE				(RZG3S_DDR1_BASE - RZG3S_DDR0_BASE)
#define RZG3S_DDR1_SIZE				(RZG3S_PCIe0_BASE - RZG3S_DDR1_BASE)

/*
 *  0x20000 has been chosen as FIP base as that leaves room at start of xSPI Flash
 * to store a 128K BL2 image.
 */
#define RZG3S_BL2_SIZE_MAX			(0x00020000U)	/* This value is not checked/enforced anywhwere */
#define RZG3S_SPIROM_FIP_BASE		(RZG3S_XSPI_MEMORY_MAP_BASE + RZG3S_BL2_SIZE_MAX)
#define RZG3S_SPIROM_FIP_SIZE		(RZG3S_PCIe_MIRROR_BASE - RZG3S_SPIROM_FIP_BASE)

#define RZG3S_EMMC_FIP_BASE			(PARAMS_BASE + PARAMS_SIZE)				//TODO: KTG: Confirm
#define RZG3S_EMMC_FIP_SIZE			(0x00078000UL)							//TODO: KTG: Confirm

#define RZG3S_SYC_INCK_HZ			(24000000UL)							//TODO: KTG: Update
#define RZG3S_UART_INCK_HZ			(100000000UL)							//TODO: KTG: Update	
#define RZG3S_UART_BARDRATE			(115200UL)

/* Boot Info base address for BL2 */
#define RZG3S_BOOTINFO_BASE			(RZG3S_ASRAM_BASE)
#define RZG3S_BOOTINFO_SIZE			(0x3000)

/* Definitions used in common code */

/* Base address where parameters to BL31 are stored */
#define PARAMS_BASE					(0x08104000 + RZG3S_BL2_SIZE_MAX)		//TODO: KTG: Confirm
#define PARAMS_SIZE					(0x1000UL)								//TODO: KTG: Confirm

#define RZ_SOC_BOOTINFO_BASE		RZG3S_BOOTINFO_BASE

#define RZ_SOC_SYC_BASE				RZG3S_SYC_BASE

#define RZ_SOC_GICD_BASE			RZG3S_GICD_BASE
#define RZ_SOC_GICR_BASE			RZG3S_GICR_BASE

#define RZ_SOC_SPIROM_FIP_BASE		RZG3S_SPIROM_FIP_BASE
#define RZ_SOC_SPIROM_FIP_SIZE		RZG3S_SPIROM_FIP_SIZE

#define RZ_SOC_EMMC_FIP_BASE		RZG3S_EMMC_FIP_BASE
#define RZ_SOC_EMMC_FIP_SIZE		RZG3S_EMMC_FIP_SIZE

#define RZ_SOC_SYSC_BASE_DEVID		SYS_LSI_DEVID
#define RZ_SOC_OTP_BASE_DEVID		(RZG3S_OTP_BASE + 0x1174)		/* OTPPRODUCT */
#define RZ_SOC_OTP_BASE_CHIPID		(RZG3S_OTP_BASE + 0x114C)		/* OTPCPID0 */

#define SYS_BASE					RZG3S_SYSC_BASE
#define PFC_BASE					RZG3S_GPIO_BASE
#define CPG_BASE					RZG3S_CPG_BASE
#define XSPI_BASE					RZG3S_XSPI_BASE

/* eMMC registers */
#define MMC0_SD_BASE				RZG3S_SD0_BASE
#define MMC1_SD_BASE				RZG3S_SD1_BASE
#define MMC2_SD_BASE				RZG3S_SD2_BASE

#endif /* __RZ_SOC_DEF_H__ */
